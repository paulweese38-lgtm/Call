  private detectOutdatedInformation(accountData: any): boolean {
    // Logic to detect information that should be removed
    const sevenYearsAgo = new Date();
    sevenYearsAgo.setFullYear(sevenYearsAgo.getFullYear() - 7);

    return new Date(accountData.lastActivity) < sevenYearsAgo &&
           (accountData.status === 'late' || accountData.status === 'collection');
  }

  private isRecentAccount(openedDate: string): boolean {
    const accountAge = new Date().getTime() - new Date(openedDate).getTime();
    const daysSinceOpen = accountAge / (1000 * 60 * 60 * 24);
    return daysSinceOpen < 30; // Less than 30 days old
  }

  private async createDisputeCase(
    accountData: any,
    type: string,
    description: string,
    availableEvidence: any[]
  ): Promise<DisputeCase> {
    const template = this.templates.find(t => t.category === type) || this.templates[0];
    const disputeId = `dispute_${Date.now()}_${Math.random().toString(36).substr(2, 9)}`;

    // Calculate confidence and impact based on available evidence and dispute type
    const confidence = this.calculateConfidence(type, availableEvidence);
    const impactScore = this.calculateImpactScore(type, accountData);

    const dispute: DisputeCase = {
      id: disputeId,
      accountId: accountData.id,
      bureau: 'all', // Default to all bureaus
      type: type as any,
      severity: this.calculateSeverity(type, impactScore),
      description,
      evidence: availableEvidence.map((evidence: any, index: number) => ({
        id: `evidence_${index}`,
        type: this.categorizeEvidence(evidence),
        title: evidence.title || `Evidence ${index + 1}`,
        description: evidence.description || '',
        fileUrl: evidence.fileUrl,
        fileName: evidence.fileName,
        fileSize: evidence.fileSize,
        uploadDate: new Date().toISOString(),
        verified: false,
        relevanceScore: this.calculateRelevanceScore(type, evidence)
      })),
      status: 'draft',
      timeline: [{
        date: new Date().toISOString(),
        event: 'Dispute analysis initiated',
        description: `AI analysis identified potential ${type} dispute opportunity`,
        status: 'completed',
        automated: true
      }],
      impactScore,
      confidence,
      legalGrounds: template.legalBases,
      statutoryReferences: [
        '15 U.S.C. § 1681i - Procedure in case of disputed accuracy',
        '15 U.S.C. § 1681c - Restrictions on investigative consumer reports',
        '15 U.S.C. § 1681n - Consumer reports; enforcement'
      ],
      autoGenerated: true
    };

    this.activeDisputes.set(disputeId, dispute);
    return dispute;
  }

  private calculateConfidence(type: string, evidence: any[]): number {
    const baseConfidence: Record<string, number> = {
      'fraudulent_account': 85,
      'paid_in_full': 80,
      'outdated_information': 90,
      'inaccurate_information': 70,
      'duplicate_entry': 75
    };

    let confidence = baseConfidence[type] || 60;

    // Boost confidence based on evidence
    const evidenceScore = Math.min(evidence.length * 10, 30);
    confidence += evidenceScore;

    // Boost for high-quality evidence
    const qualityEvidence = evidence.filter((e: any) =>
      e.type === 'payment_receipt' || e.type === 'contract_agreement' || e.type === 'id_document'
    ).length;
    confidence += qualityEvidence * 15;

    return Math.min(confidence, 95);
  }

  private calculateImpactScore(type: string, accountData: any): number {
    const baseImpact: Record<string, number> = {
      'fraudulent_account': 50,
      'paid_in_full': 30,
      'outdated_information': 40,
      'inaccurate_information': 25,
      'duplicate_entry': 35
    };

    let impact = baseImpact[type] || 20;

    // Adjust based on account balance and status
    if (accountData.balance > 1000) impact += 10;
    if (accountData.status === 'collection') impact += 15;
    if (accountData.status === 'charge_off') impact += 20;

    return Math.min(impact, 100);
  }

  private calculateSeverity(type: string, impactScore: number): 'minor' | 'moderate' | 'major' | 'critical' {
    if (type === 'fraudulent_account' || impactScore >= 50) return 'critical';
    if (impactScore >= 35) return 'major';
    if (impactScore >= 20) return 'moderate';
    return 'minor';
  }

  private categorizeEvidence(evidence: any): any {
    // Auto-categorize evidence based on filename, description, or other attributes
    const filename = evidence.fileName?.toLowerCase() || '';
    const description = evidence.description?.toLowerCase() || '';

    if (filename.includes('receipt') || description.includes('payment')) {
      return 'payment_receipt';
    }
    if (filename.includes('contract') || description.includes('agreement')) {
      return 'contract_agreement';
    }
    if (filename.includes('id') || filename.includes('license') || description.includes('identification')) {
      return 'id_document';
    }
    if (filename.includes('bank') || filename.includes('statement')) {
      return 'bank_statement';
    }
    if (filename.includes('police') || description.includes('police report')) {
      return 'police_report';
    }

    return 'other';
  }

